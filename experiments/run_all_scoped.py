"""Section-5 scope end-to-end: runs both datasets and writes results/.

Reproduces every result from the "SCOPE FOR THIS TASK" section:

    python -m experiments.run_all_scoped
      (or:  python experiments/run_all_scoped.py)

Writes:
    results/results.csv            one row per (dataset, method)
    results/bar_chart_f1_auroc.png two grouped bar charts
    results/tradeoff_scatter.png   forgetting-vs-utility scatter (+ cost size)
    results/README.md              how to read + regenerate
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.chdir(ROOT)                  # results/ and .cache/ resolve relative to repo root

import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from src.config import load_config
from src.run_experiment import run_dataset


def main() -> None:
    cfg = load_config()
    rows = []
    for ds in ["pneumonia", "path"]:
        res, _hist = run_dataset(ds, cfg)
        rows.extend(res)

    df = pd.DataFrame(rows)
    out = ROOT / "results"
    out.mkdir(exist_ok=True)

    # Relative cost columns (vs Retrain = 100%) per dataset.
    df["time_rel_to_retrain_pct"] = df.groupby("dataset")["unlearn_time_s"].transform(
        lambda s: (s / s.loc[df.loc[s.index, "method"] == "retrain"].iloc[0] * 100.0)
    )
    df["comm_rel_to_retrain_pct"] = df.groupby("dataset")["comm_bytes"].transform(
        lambda s: (s / s.loc[df.loc[s.index, "method"] == "retrain"].iloc[0] * 100.0)
    )
    df.to_csv(out / "results.csv", index=False)
    print("\n=== RESULTS (CSV rows) ===")
    print(df.to_string(index=False))

    _make_plots(df, out)
    _write_readme(out, df)


def _make_plots(df: pd.DataFrame, out: Path) -> None:
    methods = ["retrain", "finetune", "head_only_kaf"]
    datasets = ["pneumonia", "path"]
    palette = {"retrain": "#4B4AA8", "finetune": "#E07B39", "head_only_kaf": "#1F7EA8"}

    # ---- Bar chart: MIA AUROC (lower=better) and retained F1 (higher=better) ----
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
    for ax, metric, label, good in [(axes[0], "mia_auroc", "MIA AUROC (lower = better forgetting)", "min"),
                                    (axes[1], "retained_f1", "Retained weighted F1 (higher = better utility)", "max")]:
        width = 0.26
        for i, ds in enumerate(datasets):
            sub = df[(df.dataset == ds) & (df.method.isin(methods))]
            for j, m in enumerate(methods):
                v = sub[sub.method == m][metric].iloc[0]
                ax.bar(i * (len(methods) + 0.6) + j * width, v, width,
                       color=palette[m], label=(m if i == 0 else None))
        ax.set_title(label, fontsize=9)
        ax.set_xticks([i * (len(methods) + 0.6) + width for i in range(len(datasets))])
        ax.set_xticklabels([d.upper() for d in datasets], fontsize=9)
        ax.set_ylim(bottom=0)
        if good == "min":
            ax.axhline(0.5, color="#999", ls="--", lw=0.8)
            ax.text(0.02, 0.52, "random (0.5)", fontsize=7, color="#666")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=3, frameon=False, fontsize=9)
    fig.tight_layout(rect=[0, 0.06, 1, 1])
    fig.savefig(out / "bar_chart_f1_auroc.png", dpi=160)
    plt.close(fig)

    # ---- Trade-off scatter: forgetting vs utility, annotated by cost ----
    fig, ax = plt.subplots(figsize=(8, 5.2))
    for ds in datasets:
        sub = df[(df.dataset == ds) & (df.method.isin(methods))]
        for _, r in sub.iterrows():
            ax.scatter(r["mia_auroc"], r["retained_f1"], s=90,
                       color=palette[r["method"]], edgecolor="k", linewidth=0.5, zorder=3)
            ax.annotate(f"{r['method'][:7]}\n{ds.upper()}", (r["mia_auroc"], r["retained_f1"]),
                        textcoords="offset points", xytext=(6, 6), fontsize=8)
    ax.axvline(0.5, color="#999", ls="--", lw=0.8)
    ax.set_xlabel("MIA AUROC  (lower = better forgetting)")
    ax.set_ylabel("Retained weighted F1  (higher = better utility)")
    ax.set_title("Forgetting vs utility trade-off by method and dataset")
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(out / "tradeoff_scatter.png", dpi=160)
    plt.close(fig)


def _write_readme(out: Path, df: pd.DataFrame) -> None:
    txt = f"""# Results — Section-5 scope run

This folder is auto-generated by `experiments/run_all_scoped.py`:

    python -m experiments.run_all_scoped

The single entrypoint trains a FedAvg baseline on each dataset, removes client 0,
and applies three unlearning methods (Retrain, Fine-tune, Head-only KAF), then writes:

* `results.csv` — one row per (dataset, method). Columns:

| column | meaning |
|---|---|
| dataset | `pneumonia` or `path` |
| method | `baseline`, `retrain`, `finetune`, `head_only_kaf` |
| mia_auroc | membership-inference AUROC — **lower = better forgetting** (0.5 = random) |
| retained_f1 | weighted F1 on the global held-out test set (**higher = better utility**) |
| probe_acc | residual accuracy on the removed client's held-out tuples (secondary signal) |
| n_rounds | FedAvg rounds used |
| comm_bytes | communication proxy = rounds x participating clients x head bytes |
| unlearn_time_s | wall-clock seconds of the unlearning procedure only |
| time_rel_to_retrain_pct / comm_rel_to_retrain_pct | cost relative to Retrain = 100% |

* `bar_chart_f1_auroc.png` — grouped bars: MIA AUROC (lower better) and retained F1.
* `tradeoff_scatter.png` — each method's forgetting-vs-utility point.

## How to read it
A good method sits in the BOTTOM-RIGHT of the trade-off: it forgets well
(low MIA AUROC) while keeping high utility (high retained F1), and at lower cost
than full retraining. Retrain defines the gold standard; approximate methods
should be judged against it on all three axes.
"""
    (out / "README.md").write_text(txt, encoding="utf-8")


if __name__ == "__main__":
    main()
